export type RepairTopic = "memories" | "people" | "places" | "world" | "progress" | "restore";
export type RepairValue = string | number | boolean;
export type RepairPerson = { id: string; name: string };
export type RepairField = {
  key: string;
  label: string;
  value: RepairValue;
  type: "text" | "number" | "choice" | "boolean";
  options?: { value: string; label: string }[];
  min?: number;
  max?: number;
};
export type RepairRecord = {
  id: string;
  topic: RepairTopic;
  title: string;
  summary: string;
  fields: RepairField[];
  source: string[];
  actions: { id: string; label: string }[];
  people?: { id: string; name: string; text?: string; forgotten?: boolean }[];
  related: { id: string; title: string }[];
  revision?: number;
  token?: string;
  creating?: boolean;
  subjects?: string[];
};
export type RepairRequest = {
  operationId: string;
  recordId: string;
  action: string;
  values: Record<string, RepairValue>;
  knowers: string[];
  expectedRecord: string;
  personId?: string;
};
export type RepairChange = { label: string; before: string; after: string };
export type RepairReview = {
  kind: "repair" | "undo" | "restore";
  id: string;
  token: string;
  title: string;
  changes: RepairChange[];
  affected: string[];
  related: RepairRecord["related"];
  checkpoint: boolean;
  undoAvailable: boolean;
  memory?: { creating: boolean; people: string[] };
};
export type RepairHistoryEntry = {
  id: string;
  title: string;
  at: string;
  changes: RepairChange[];
  affected: string[];
  undone: boolean;
  canUndo: boolean;
};
export type RepairCheckpoint = {
  id: string;
  title: string;
  at: string;
  records: number;
  token: string;
  mode: "automatic" | "manual";
};
export type RepairIndex = {
  seed: string;
  identity: string;
  records: RepairRecord[];
  history: RepairHistoryEntry[];
  historyOffset: number;
  historyTotal: number;
  checkpoints: RepairCheckpoint[];
  checkpointOffset: number;
  checkpointTotal: number;
  sceneOpen: boolean;
  people: RepairPerson[];
};
export type RepairRecordPage = { records: RepairRecord[]; total: number; next: number | null; creation?: RepairRecord };
